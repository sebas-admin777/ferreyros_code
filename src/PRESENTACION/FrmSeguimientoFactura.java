    private void generarPDF() {
    try {
        com.itextpdf.text.Document doc = new com.itextpdf.text.Document();
        com.itextpdf.text.pdf.PdfWriter.getInstance(doc, new java.io.FileOutputStream("reporte_seguimiento.pdf"));

        doc.open();

        // LOGO
        try {
            com.itextpdf.text.Image logo = com.itextpdf.text.Image.getInstance("src/imagen/Ferreyros.png");
            logo.scaleToFit(100, 100);
            logo.setAlignment(com.itextpdf.text.Image.ALIGN_CENTER);
            doc.add(logo);
        } catch (Exception e) {
            System.out.println("Logo no encontrado");
        }

        // TITULO
        com.itextpdf.text.Paragraph titulo = new com.itextpdf.text.Paragraph(
                "REPORTE DE SEGUIMIENTO",
                com.itextpdf.text.FontFactory.getFont(
                        com.itextpdf.text.FontFactory.HELVETICA_BOLD, 16
                )
        );
        titulo.setAlignment(com.itextpdf.text.Element.ALIGN_CENTER);
        doc.add(titulo);

        doc.add(new com.itextpdf.text.Paragraph("\n"));

        // TABLA
        com.itextpdf.text.pdf.PdfPTable tablaPDF = new com.itextpdf.text.pdf.PdfPTable(6);

        tablaPDF.addCell("Factura");
        tablaPDF.addCell("Pedido");
        tablaPDF.addCell("Transacción");
        tablaPDF.addCell("Empleado");
        tablaPDF.addCell("Estado");
        tablaPDF.addCell("Sucursal");

        for (int i = 0; i < tablaSeguimiento.getRowCount(); i++) {
            tablaPDF.addCell(tablaSeguimiento.getValueAt(i, 0).toString());
            tablaPDF.addCell(tablaSeguimiento.getValueAt(i, 1).toString());
            tablaPDF.addCell(tablaSeguimiento.getValueAt(i, 2).toString());
            tablaPDF.addCell(tablaSeguimiento.getValueAt(i, 3).toString());
            tablaPDF.addCell(tablaSeguimiento.getValueAt(i, 4).toString());
            tablaPDF.addCell(tablaSeguimiento.getValueAt(i, 5).toString());
        }

        doc.add(tablaPDF);
        doc.close();

        JOptionPane.showMessageDialog(this, "PDF generado correctamente");

    } catch (Exception e) {
        e.printStackTrace();
    }
}
