     private void cargarCombos() {
        cbFactura.removeAllItems();
        cbPedido.removeAllItems();
        cbTransaccion.removeAllItems();
        cbEmpleado.removeAllItems();

        // Usamos el controlador para traer datos reales de Oracle
        for (String f : c.listarFacturas()) cbFactura.addItem(f);
        for (String p : c.listarPedidos()) cbPedido.addItem(p);
        for (String t : c.listarTransacciones()) cbTransaccion.addItem(t);
        for (String e : c.listarEmpleados()) cbEmpleado.addItem(e);
    }

    private void listar() {
        llenarTabla(c.listar());
    }

    public void llenarTabla(ArrayList<SeguimientoFactura> lista) {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.setColumnIdentifiers(new Object[]{
            "Factura ID", "Pedido ID", "Transacción", "Empleado", "Estado", "Sucursal"
        });

        for (SeguimientoFactura s : lista) {
            modelo.addRow(new Object[]{
                s.getIdFactura(),
                s.getIdPedido(),
                s.getIdTransaccion(),
                s.getIdEmpleado(),
                s.getEstado(),
                s.getSucursal()
            });
        }
        tablaSeguimiento.setModel(modelo);
    }

    private SeguimientoFactura capturarDatos() {
        SeguimientoFactura s = new SeguimientoFactura();
        s.setIdFactura(cbFactura.getSelectedItem().toString());
        s.setIdPedido(cbPedido.getSelectedItem().toString());
        s.setIdTransaccion(cbTransaccion.getSelectedItem().toString());
        s.setIdEmpleado(cbEmpleado.getSelectedItem().toString());
        // Valores fijos para los nuevos campos si no tienes combos aún
        s.setEstado("PENDIENTE");
        s.setSucursal("LIMA - CENTRAL");
        return s;
    }
   
    
    

