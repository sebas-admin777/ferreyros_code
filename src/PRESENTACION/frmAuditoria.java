    private void btnInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertarActionPerformed
        try {
        Auditoria a = new Auditoria(
            Integer.parseInt(txtIdAuditoria.getText()),
            txtIpOrigen.getText(),
            txtUsuario.getText(),
            txtAccion.getText()
        );
        AuditoriaService service = new AuditoriaService();
        service.registrarAuditoria(a);
        JOptionPane.showMessageDialog(this, "Registro insertado correctamente");
        
        // Actualizar combo box con nuevo ID
        cmbSeleccion.addItem(String.valueOf(a.getIdAuditoria()));
        
        listarTodo();
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Error al insertar: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnInsertarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        try {
        int id = Integer.parseInt(txtIdAuditoria.getText());
        AuditoriaService service = new AuditoriaService();
        service.eliminarAuditoria(id);
        JOptionPane.showMessageDialog(this, "Registro eliminado correctamente");
        
        // Quitar ID del combo
        cmbSeleccion.removeItem(String.valueOf(id));
        
        listarTodo();
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Error al eliminar: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnListarTodoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarTodoActionPerformed
        listarTodo();
}

private void listarTodo() {
    try {
        AuditoriaService service = new AuditoriaService();
        List<Auditoria> lista = service.listarAuditorias();
        DefaultTableModel modelo = (DefaultTableModel) tblAuditoria.getModel();
        modelo.setRowCount(0); // limpiar tabla
        for (Auditoria a : lista) {
            modelo.addRow(new Object[]{
                a.getIdAuditoria(),
                a.getIpOrigen(),
                a.getUsuario(),
                a.getAccion()
            });
        }
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Error al listar: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnListarTodoActionPerformed

