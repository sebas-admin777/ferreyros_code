    private void btnActividadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActividadActionPerformed
        try {
        int id = Integer.parseInt((String) cmbSeleccion.getSelectedItem());
        AuditoriaService service = new AuditoriaService();
        Auditoria a = service.buscarAuditoria(id);
        if (a != null) {
            txtIdAuditoria.setText(String.valueOf(a.getIdAuditoria()));
            txtIpOrigen.setText(a.getIpOrigen());
            txtUsuario.setText(a.getUsuario());
            txtAccion.setText(a.getAccion());
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró el registro");
        }
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Error al buscar: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnActividadActionPerformed

    private void cmbSeleccionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbSeleccionActionPerformed
        try {
        AuditoriaService service = new AuditoriaService();
        List<Auditoria> lista = service.listarAuditorias();
        cmbSeleccion.removeAllItems();
        for (Auditoria a : lista) {
            cmbSeleccion.addItem(String.valueOf(a.getIdAuditoria()));
        }
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Error al cargar combo: " + ex.getMessage());
    }
    }//GEN-LAST:event_cmbSeleccionActionPerformed

