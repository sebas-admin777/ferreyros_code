    private void btnAumentarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAumentarActionPerformed
        Equipo e = new Equipo(
            Integer.parseInt(txtIdSucursal.getText()),
            Integer.parseInt(txtIdEquipo.getText()),
            txtSerie.getText(),
            txtModelo.getText(),
            txtEstado.getText()
        );
        servicio.guardar(e);
        listar();
    }//GEN-LAST:event_btnAumentarActionPerformed

    private void btnClasificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnClasificarActionPerformed
        List<Equipo> lista = servicio.obtenerOrdenadosPorIdDesc();
        DefaultTableModel modelo = (DefaultTableModel) tblEquipo.getModel();
        modelo.setRowCount(0);
        for (Equipo e : lista) {
            modelo.addRow(new Object[]{
                e.getIdSucursal(),
                e.getIdEquipo(),
                e.getSerie(),
                e.getModelo(),
                e.getEstado()
            });
        }
    }//GEN-LAST:event_btnClasificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblEquipo.getSelectedRow();
        if (fila >= 0) {
            int id = (int) tblEquipo.getValueAt(fila, 1); // columna ID_Equipo
            servicio.eliminar(id);
            listar();
        } else {
            JOptionPane.showMessageDialog(this, "Seleccione un registro para eliminar");
        }   
    }//GEN-LAST:event_btnEliminarActionPerformed

