    // ── Carga todos los equipos en la tabla ──────────────────
    private void listar() {
        List<Equipo> lista = servicio.obtener();
        DefaultTableModel modelo = (DefaultTableModel) tblEquipo.getModel();
        modelo.setRowCount(0);
        if (lista != null) {
            for (Equipo e : lista) {
                modelo.addRow(new Object[]{
                    e.getIdSucursal(),
                    e.getIdEquipo(),
                    e.getSerie(),
                    e.getModelo(),
                    e.getEstado()
                });
            }
        }
    }

