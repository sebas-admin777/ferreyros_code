    public void listar() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID");
        modelo.addColumn("Cliente");
        modelo.addColumn("Tipo");
        modelo.addColumn("Fecha Inicio");
        modelo.addColumn("Fecha Fin");

        // Usamos servicio.listar() que devuelve List<Contrato>
        List<Contrato> lista = servicio.listar();
        for (Contrato c : lista) {
            modelo.addRow(new Object[]{
                c.getIdContrato(),
                c.getIdCliente(),
                c.getTipo(),
                c.getFechaInicio(),
                c.getFechaFin()
            });
        }
        tblContrato.setModel(modelo);
    }

    public void cargarComboBox() {
        try {
            cboFiltroId.removeAllItems();
            cboFiltroId.addItem("Seleccionar");

            // Usamos el método listar() del servicio de Sebastián
            List<Contrato> lista = servicio.listar();

            for (Contrato item : lista) {
                // Agregamos el ID del contrato al ComboBox
                cboFiltroId.addItem(String.valueOf(item.getIdContrato()));
            }
        } catch (Exception e) {
            System.err.println("Error al cargar ComboBox: " + e.getMessage());
        }
    }

    private void filtrarTablaPorId(int id) {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID");
        modelo.addColumn("Cliente");
        modelo.addColumn("Tipo");
        modelo.addColumn("Fecha Inicio");
        modelo.addColumn("Fecha Fin");

        Contrato c = servicio.buscar(id);
        if (c != null) {
            modelo.addRow(new Object[]{
                c.getIdContrato(),
                c.getIdCliente(),
                c.getTipo(),
                c.getFechaInicio(),
                c.getFechaFin()
            });
        }
        tblContrato.setModel(modelo);
    }
