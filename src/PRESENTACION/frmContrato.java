    private void cboFiltroIdItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cboFiltroIdItemStateChanged
        if (java.awt.event.ItemEvent.SELECTED == evt.getStateChange()) {
            String seleccionado = cboFiltroId.getSelectedItem().toString();
            
            if (!seleccionado.equals("Seleccionar")) {
                int id = Integer.parseInt(seleccionado);
                filtrarTablaPorId(id);
            } else {
                listar(); // Si elige "Seleccionar", mostramos todo
            }
        } else {
        }
    }//GEN-LAST:event_cboFiltroIdItemStateChanged

